/**
 * Represents the ranks of cards in a standard Bridge deck.
 *
 * The order of the values follows their normal card ranking,
 * from Two (lowest) to Ace (highest).
 */
public enum Rank {

    /** Two, the lowest rank. */
    TWO,

    /** Three. */
    THREE,

    /** Four. */
    FOUR,

    /** Five. */
    FIVE,

    /** Six. */
    SIX,

    /** Seven. */
    SEVEN,

    /** Eight. */
    EIGHT,

    /** Nine. */
    NINE,

    /** Ten. */
    TEN,

    /** Jack. */
    JACK,

    /** Queen. */
    QUEEN,

    /** King. */
    KING,

    /** Ace, the highest rank. */
    ACE
}