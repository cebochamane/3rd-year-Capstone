/**
 * Represents the suits used in Bridge.
 *
 * NT (No Trump) is included to represent a No Trump contract.
 */
public enum Suit {

    /** Clubs suit. */
    CLUBS,

    /** Diamonds suit. */
    DIAMONDS,

    /** Hearts suit. */
    HEARTS,

    /** Spades suit. */
    SPADES,

    /** No Trump contract. */
    NT
}